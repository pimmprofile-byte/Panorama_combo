def public_card(cid: str):
    """전체공개된 카드로 나가는 몫. 여기 안 적은 필드는 플레이어에게 안 갑니다.

    ★ 퍼즐에서 나가는 것은 `prompt` 뿐입니다.
      `answer` 는 당연하고, **`hint` 도 안 나갑니다** — 「막히면 주는 한 줄」이
      처음부터 보이면 퍼즐이 그냥 읽는 글이 됩니다. 몇 번 틀린 사람에게만 열어주는
      배선은 엔진 쪽 일이고, 그때도 개인 칸으로만 내려갑니다(puzzle_hint 참고).
    """
    c = get_card(cid)
    if not c:
        return None
    out = {"id": c["id"], "loc": c["loc"], "locName": c["locName"], "round": c["round"],
           "title": c["title"], "text": c["text"], "bait": c.get("bait", False),
           "spot": c.get("spot", ""), "unlocks": c.get("unlocks", ""),
           "item": bool(c.get("item"))}
    p = c.get("puzzle")
    if p:
        out["puzzle"] = {"prompt": p.get("prompt", "")}
    return out


def puzzle_hint(cid: str) -> str:
    """막힌 사람에게만 열어주는 한 줄. 엔진이 「몇 번 틀렸는가」를 세고 부릅니다.

    `public_card()` 로는 절대 안 나갑니다 — 그래서 이 함수가 따로 있습니다.
    """
    p = (get_card(cid) or {}).get("puzzle") or {}
    return p.get("hint", "")


def check_puzzle(cid: str, got: str) -> bool:
    """암호 판정. **반드시 서버에서** 합니다.

    한글은 완성형(U+AC00)과 자모 조합(U+1100 U+1161)이 눈으로 같고 `==` 로 다릅니다 —
    안드로이드 키보드와 맥 IME 가 서로 다르게 보냅니다. NFC 로 모으고, 공백을 전부
    빼고, 소문자로 내립니다. 정답이 숫자만이면 입력에서도 숫자만 남깁니다.
    그 이상은 안 합니다 — 흔들림을 다 받아주려면 규칙이 끝없이 늡니다.
    대신 `answer` 를 목록으로 받아 해결합니다.
    """
    import re
    import unicodedata

    def norm(s):
        s = unicodedata.normalize("NFC", str(s or ""))
        return re.sub(r"\s+", "", s).lower()

    p = (get_card(cid) or {}).get("puzzle") or {}
    want = p.get("answer")
    if want is None:
        return False
    wants = want if isinstance(want, (list, tuple)) else [want]
    for w in wants:
        w2 = norm(w)
        g2 = norm(got)
        if w2.isdigit():
            g2 = "".join(ch for ch in g2 if ch.isdigit())
        if w2 and w2 == g2:
            return True
    return False


