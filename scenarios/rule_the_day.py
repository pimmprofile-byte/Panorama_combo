# 「조용히 받는 것」에 붙는 이름표. 막 이름과 «달라야» 합니다 — 서버의 막머리 처리
# (`_seed_phase_lines`)가 「when 이 지금 막 이름과 같은 것」만 대화창에 올리기 때문에,
# 이 이름표를 달면 그 줄은 대화창을 타지 않고 「내 정보」에만 남습니다.
QUIET_LABEL = "혼자 떠오른 것"


def memory_up_to(cid: str, current_seq: int, crisis_solved=None) -> list:
    """그 배역에게 지금까지 떠오른 것.

    ★ `quiet: True` 인 항목은 **대화창에 안 올라갑니다.** 2차 토론 뒤에 셋이 동시에
      받는 것들이 그렇습니다 — 세상의 끝 앞의 기억도, 데이지의 공략도 «혼자 읽는»
      것이라야 위장이 성립합니다. 자동으로 대화창에 흘러버리면 그 자리에서 다 새고,
      데이비드가 그걸 숨기고 싶어 한다는 설정도 무의미해집니다.

      엔진을 안 고치고 이걸 만드는 길이 이름표입니다 — `when` 을 막 이름이 아닌
      `QUIET_LABEL` 로 돌려주면 막머리 처리가 그 줄을 그냥 지나칩니다.
      「내 정보」의 조각 목록은 이 함수의 결과를 통째로 쓰므로 거기에는 그대로 뜹니다.
    """
    out = []
    for m in MEMORY.get(cid, []):
        if m["seq"] <= current_seq:
            when = QUIET_LABEL if m.get("quiet") else phase_by_seq(m["seq"])["name"]
            out.append({"when": when, "text": m["text"]})
    return out


