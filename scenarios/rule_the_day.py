def event_cut(key: str):
    """엔진이 「phase:{seq}」·「gate:{loc}」·「vanish」·「dev」·「escape:ok」·
    「ending:{키}」 같은 키로 부릅니다. 없는 키면 None 을 돌려주면 됩니다.

    엔딩 컷은 **엔딩이 확정되는 순간**에 불러야 합니다. 막에 들어서는 시점에는
    아직 표가 다 안 모여 엔딩이 None 일 수 있습니다.
    """
    if key.startswith("ending:"):
        return ENDING_CUTS.get(key.split(":", 1)[1])
    return EVENT_CUTS.get(key)


# ── 개발자 전환 판정 ─────────────────────────────────────────────
def dev_pick_from(picks: dict, asked=None, held=None) -> str:
    """개발자가 누구에게 로그인하는가.

    **「진상에 가까운 답」 = 「이 세상이 게임임에 가까이 간 답」입니다.** 깨달으면
    그게 버그이므로 덮어씁니다 — 그게 이 판정의 전부입니다.

    `picks`  {배역id: 선지id} — 2차 토론에서 고른 것. 이게 정본입니다.
    `asked`  [{"by","q"}]     — 질문지 기록. 선지가 아직 안 붙어 있는 동안의 보조 축.
    `held`   {배역id: [카드id]} — 쥐었거나 공개한 것. 같은 보조 축.

    `pool` 밖(데이지)은 애초에 안 셉니다 — 캐릭터가 아니라 플레이어라서
    접속할 대상이 아닙니다(DEV_PICK["poolWhy"]). 동점이면 `tiebreak`.
    """
    pool = list(DEV_PICK["pool"])
    score = {rid: 0 for rid in pool}
    for rid, oid in (picks or {}).items():
        if rid not in score:
            continue
        opt = next((o for o in DEV_PICK["options"] if o["id"] == oid), None)
        if opt:
            score[rid] += int(opt.get("near", 0))
    for row in (asked or []):
        rid = row.get("by")
        if rid in score:
            score[rid] += int(DEV_PICK["qw"].get(row.get("q"), 0))
    for rid, cards in (held or {}).items():
        if rid not in score:
            continue
        for cid in cards or []:
            score[rid] += int(DEV_PICK["cw"].get(cid, 0))
    top = max(score.values()) if score else 0
    lead = sorted(r for r, v in score.items() if v == top)
    if len(lead) == 1:
        return lead[0]
    return DEV_PICK["tiebreak"]


# ── 엔딩 선지 판정 ───────────────────────────────────────────────
def judge_ending_picks(picks: dict, dev_id: str = "") -> dict:
    """마지막 질문(10막)의 선지를 읽는다.

    `picks`  {배역id: 선지id}
    `dev_id` 개발자에게 먹힌 사람(있으면). 그 사람의 답은 판정에서 뺍니다 —
             자기가 아는 것을 고르는 것은 「닿았다」가 아닙니다.

    돌려주는 것 —
      seen     이 세상이 무엇인지 «닿은» 배역 id 목록
      devKept  먹힌 사람 말고 **다른 둘이 끝내 못 닿았는가**. 개발자 단독 우승 조건
    """
    opt = {o["id"]: o for o in ENDING_OPTIONS}
    seen = sorted(rid for rid, oid in (picks or {}).items()
                  if opt.get(oid, {}).get("sees"))
    others = [rid for rid in (picks or {}) if rid != dev_id]
    dev_kept = bool(dev_id) and all(not opt.get(picks[r], {}).get("sees") for r in others)
    return {"seen": seen, "devKept": dev_kept}


