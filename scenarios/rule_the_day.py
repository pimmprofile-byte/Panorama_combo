# ── 엔딩 ─────────────────────────────────────────────────────────
def compute_ending(votes: dict, ctx=None):
    """엔딩을 고른다.

    `votes` 는 `{지목한 배역id: 지목당한 배역id}`.
    `ctx`   는 엔진이 넘겨주는 방 상태입니다(안 넘겨주는 엔진도 있어서 기본값 None).

        {"escape":  {"done": True/False},          방탈출 성패
         "decision": {배역id: 선지id},              마지막 질문의 답
         "dev":      {"who": 배역id},               개발자에게 먹힌 사람
         "items":    {배역id: [카드id]},            인벤토리
         "solved":   {카드id: 배역id}}              푼 퍼즐

    갈리는 순서 —
      1. 문이 열렸는가
         1-1. 열렸는데 다른 둘이 끝내 «못 닿았다»  →  개발자 단독 우승
         1-2. 열렸고 누군가 닿았다                →  진엔딩(전원 탈출)
      2. 안 열렸는데 진범을 맞혔는가              →  잡았으나 갇힘
      3. 그 외                                    →  아무것도 못 밝힘

    **탈출이 지목보다 위에 있습니다.** 그게 「각자 자기 점수를 포기해야 열린다」의 뜻입니다.
    """
    if len(votes) < len(CHARACTERS):
        return None
    ctx = ctx or {}
    tally = {}
    for t in votes.values():
        tally[t] = tally.get(t, 0) + 1
    top = max(tally.values())
    lead = sorted(t for t, v in tally.items() if v == top)
    # 표가 갈리면 아무도 안 잡힌 것으로 본다. 「제일 많이 불린 이름」이 하나여야 검거다.
    caught = (len(lead) == 1 and lead[0] == CULPRIT_ID)

    escaped = _escaped(ctx)
    dev_id = (ctx.get("dev") or {}).get("who", "")
    judged = judge_ending_picks(ctx.get("decision") or {}, dev_id)

    if escaped and judged["devKept"]:
        key = "dev"
    elif escaped:
        key = "escape"
    elif caught:
        key = "caught"
    else:
        key = "dark"
    e = ENDINGS[key]
    hit = sorted(rid for rid, t in votes.items() if t == CULPRIT_ID)
    return {"key": key, "name": e["name"], "tone": e["tone"], "desc": e["desc"],
            "culprit": CULPRIT_ID, "tally": tally, "lead": lead,
            "accused": hit, "truth": TRUTH_FULL,
            "escaped": escaped, "seen": judged["seen"],
            "titlesNote": TITLES_NOTE}


def _escaped(ctx=None) -> bool:
    """문이 열렸는가.

    엔진이 `ctx["escape"]["done"]` 을 넘겨주면 그것이 정본입니다. 아직 방탈출 판정이
    안 붙었으면 `set_room_state` 로 받아둔 인벤토리로 «도구는 다 모였는가»까지만
    봅니다 — 그것도 없으면 False 라서 **진엔딩이 안 열립니다.** 그게 지금 상태입니다.
    """
    ctx = ctx or {}
    esc = ctx.get("escape") or _ROOM.get("escape") or {}
    if esc.get("done") is not None:
        return bool(esc.get("done"))
    inv = ctx.get("items") or _ROOM.get("items") or _ROOM.get("inventory") or {}
    try:
        got = {cid for ids in inv.values() for cid in ids}
    except Exception:                       # noqa: BLE001 — 판정 하나 때문에 판이 죽으면 안 된다
        return False
    return set(ESCAPE["answer"].values()) <= got


# ── 마지막 질문(10막)의 결과문 ───────────────────────────────────
def decision_report(picks: dict, extra: str = "none", barred: str = "") -> dict:
    """엔진이 「다 골랐다」고 판단했을 때 부릅니다. 화면에 읽히는 몫입니다.

    ※ 여기서 «판정 결과»를 말하지 않습니다 — 누가 무엇에 닿았는지는 엔딩에서
       한꺼번에 나옵니다. 여기서는 각자 무엇을 골랐는지만 되읽어 줍니다.
    """
    opt = {o["id"]: o for o in ENDING_OPTIONS}
    rows = []
    for c in CHARACTERS:
        oid = (picks or {}).get(c["id"], "")
        rows.append({"roleId": c["id"], "name": c["name"], "color": c["color"],
                     "label": opt.get(oid, {}).get("label", "—")})
    return {"title": "마지막으로 남긴 문장",
            "lines": [f'{r["name"]} — {r["label"]}' for r in rows],
            "rows": rows}
